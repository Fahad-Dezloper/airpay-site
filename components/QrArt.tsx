/**
 * A real QR code, drawn from its own grid of modules. It was made with the same kind of encoder
 * the app uses and reads as this project's public code repository, so scanning it off the page
 * leads somewhere harmless and never to a wallet.
 */
const ROWS = [
  "11111110001010001011101111111",
  "10000010101000111010001000001",
  "10111010000010111000001011101",
  "10111010111011110101001011101",
  "10111010010001001011101011101",
  "10000010110111011000101000001",
  "11111110101010101010101111111",
  "00000000011100100010000000000",
  "11111011110101111110010101010",
  "01000101101010011111101110001",
  "10011011101000111000000010000",
  "01001000100010101001100001010",
  "11111011111011100000000001100",
  "01011000100000100010111110001",
  "01100111010111010000110011100",
  "01000000110100000011111110010",
  "01010110101101011101010101100",
  "11100101010011001011011110101",
  "10100010101000111000101110100",
  "10100101100010111000111000010",
  "10111011010010110101111110111",
  "00000000110001001100100011111",
  "11111110110111110111101011100",
  "10000010010100010011100010010",
  "10111010100110111100111110101",
  "10111010101010001111100001111",
  "10111010100001111001111111110",
  "10000010101110001010110101010",
  "11111110101010100101001110100",
];

export function QrArt({ className = "" }: { className?: string }) {
  const n = ROWS.length;
  return (
    <svg viewBox={`0 0 ${n} ${n}`} className={className} role="img" aria-label="A QR code" shapeRendering="geometricPrecision">
      {ROWS.flatMap((row, y) =>
        [...row].map((bit, x) => (bit === "1" ? <rect key={`${x}-${y}`} x={x + 0.06} y={y + 0.06} width={0.88} height={0.88} rx={0.26} fill="#16181c" /> : null)),
      )}
    </svg>
  );
}
